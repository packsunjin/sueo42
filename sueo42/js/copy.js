// 문구 가져오기: t("C-07", { n: 3, d: 2 }) → "레벨 3 · 2일 연속"
export function t(id, vars = {}) {
  const s = COPY[id];
  if (s === undefined) throw new Error(`문구 번호 없음: ${id}`);
  return fill(s, vars);
}

// 버튼 글자: "[다시 시도]" → "다시 시도"
export function btn(id, vars = {}) {
  return unbracket(t(id, vars));
}

export function unbracket(s) {
  return s.replace(/^\[(.*)\]$/, "$1");
}

export function fill(s, vars = {}) {
  return s.replace(/\{([^{}]+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

// 글과 버튼이 섞인 문구: "해 본 단어 {k}/6 · [이어서 하기]" → { text: "해 본 단어 2/6", button: "이어서 하기" }
export function splitButton(id, vars = {}) {
  const s = t(id, vars);
  const m = s.match(/^(.*?)\s*·?\s*\[([^\]]+)\]\s*$/);
  return m ? { text: m[1].replace(/\s*·\s*$/, ""), button: m[2] } : { text: s, button: "" };
}
